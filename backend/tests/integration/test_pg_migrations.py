"""The Alembic migrations, applied to an empty Postgres, produce the schema
the models expect, and nothing has drifted between the two."""

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import Engine, inspect, text

from app.database import Base

MODEL_TABLES = {t.name for t in Base.metadata.sorted_tables}


def test_upgrade_from_empty_creates_every_model_table(pg_engine: Engine, alembic_cfg: Config):
    with pg_engine.begin() as conn:
        conn.execute(text("DROP SCHEMA public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))
    command.upgrade(alembic_cfg, "head")

    tables = set(inspect(pg_engine).get_table_names())
    assert tables == MODEL_TABLES | {"alembic_version"}


def test_database_is_at_head_after_upgrade(pg_engine: Engine, alembic_cfg: Config):
    head = ScriptDirectory.from_config(alembic_cfg).get_current_head()
    with pg_engine.connect() as conn:
        current = conn.execute(text("SELECT version_num FROM alembic_version")).scalar()
    assert current == head


def test_models_and_migrations_do_not_drift(pg_engine: Engine, alembic_cfg: Config):
    # `alembic check` raises AutogenerateDiffsDetected when a model change
    # has no migration; a clean run returns None.
    assert command.check(alembic_cfg) is None


def test_timestamps_are_stored_without_time_zone(pg_engine: Engine):
    columns = {c["name"]: c["type"] for c in inspect(pg_engine).get_columns("cards")}
    for name in ("created_at", "updated_at", "due_date"):
        assert str(columns[name]) == "TIMESTAMP", name
        assert not getattr(columns[name], "timezone", False), name


def test_foreign_keys_cascade_on_postgres(pg_engine: Engine):
    fks = {fk["constrained_columns"][0]: fk for fk in inspect(pg_engine).get_foreign_keys("cards")}
    assert fks["board_id"]["options"].get("ondelete") == "CASCADE"
    assert fks["parent_card_id"]["options"].get("ondelete") == "SET NULL"
    assert fks["assignee_id"]["options"].get("ondelete") == "SET NULL"
    assert "ondelete" not in fks["column_id"]["options"]
